                        <li>You are experiencing physical symptoms like chronic insomnia, digestive issues, or frequent panic attacks.</li>
                        <li>You feel like you cannot control your worrying.</li>
                        <li>Traditional medications haven't worked or caused intolerable side effects.</li>
