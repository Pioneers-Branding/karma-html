    <script>
        function scrollToSection(id) {
            const element = document.getElementById(id);
            if (element) {
                const headerOffset = 100;
                const elementPosition = element.getBoundingClientRect().top;
                const offsetPosition = elementPosition + window.pageYOffset - headerOffset;
                window.scrollTo({
                    top: offsetPosition,
                    behavior: "smooth"
                });
            }
        }

        function toggleBlogFAQ(button) {
            const item = button.closest('.accordion-item');
            const isOpen = item.getAttribute('data-state') === 'open';
            
            // Close all
            document.querySelectorAll('.accordion-item').forEach(el => {
                el.setAttribute('data-state', 'closed');
                const content = el.querySelector('.accordion-content');
                content.style.maxHeight = '0px';
            });
            
            // Open clicked if it was closed
            if (!isOpen) {
                item.setAttribute('data-state', 'open');
                const content = item.querySelector('.accordion-content');
                content.style.maxHeight = content.scrollHeight + "px";
            }
        }
        
        // Active TOC state based on scroll
        window.addEventListener('scroll', () => {
            let current = '';
            const sections = document.querySelectorAll('.scroll-target, #intro');
            
            sections.forEach(section => {
                const sectionTop = section.offsetTop;
                if (pageYOffset >= sectionTop - 150) {
                    current = section.getAttribute('id');
                }
            });

            document.querySelectorAll('.toc-button').forEach(button => {
                button.classList.remove('active');
                if (button.getAttribute('onclick').includes(current)) {
                    button.classList.add('active');
                }
            });
        });
    </script>
    
