                    <p class="text-xl leading-relaxed text-gray-700">
                        When seeking mental health support, navigating the different types of professionals can be confusing. You might wonder: should I see a therapist, a psychologist, or a psychiatrist? A common question that arises is: <strong>Do psychiatrists do therapy?</strong>
                    </p>
                    <p class="mt-4 text-gray-700">
                        The short answer is yes, some do. However, in modern psychiatric practice, the roles have become more specialized. While all psychiatrists are trained in psychotherapy, many primarily focus on <a href="medication-management.php" class="text-primary hover:underline font-semibold">medication management</a> and medical interventions. Let's explore the role of a psychiatrist, why this shift has occurred, what kinds of therapy they are qualified to perform, and how to find the right mental health care team for your unique needs.
                    </p>
