                            <li>1 in 5 U.S. adults experience mental illness each year.</li>
                            <li>1 in 20 U.S. adults experience serious mental illness each year.</li>
                            <li>Less than half of adults with a mental illness receive treatment.</li>
                        </ul>
                    </div>
                    <p class="mb-6">
