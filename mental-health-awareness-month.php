                <!-- Section: Recognizing the Signs -->
                <section id="recognizing-the-signs" class="mb-12 scroll-target">
                    <h2 class="text-3xl font-bold text-primary mb-6">Recognizing the Signs</h2>
                    <p class="mb-6">
                        One of the core pillars of Mental Health Awareness Month is education. Knowing the <a href="signs-your-depression-needs-professional-treatment.php" class="text-primary hover:underline">signs that someone may need professional help</a> can make a critical difference.
                    </p>
                    <ul class="list-disc pl-6 space-y-2 text-gray-700 mb-6">
                        <li><strong>Changes in Mood:</strong> Persistent sadness, irritability, or dramatic mood swings.</li>
                        <li><strong>Withdrawal:</strong> Pulling away from friends, family, and activities once enjoyed.</li>
                        <li><strong>Changes in Sleep or Appetite:</strong> Sleeping too much or too little; significant weight loss or gain.</li>
                        <li><strong>Difficulty Functioning:</strong> Struggling to perform routine tasks at work, school, or home.</li>
                        <li><strong>Unexplained Physical Ailments:</strong> Frequent headaches, stomachaches, or chronic pain without an obvious physical cause.</li>
                    </ul>
                    <p class="mb-6">
                        If you notice these signs in yourself or a loved one, it may be time to seek support. Conditions like <a href="ptsd.php" class="text-primary hover:underline">PTSD</a> or <a href="bipolar.php" class="text-primary hover:underline">Bipolar Disorder</a> require specialized professional care.
                    </p>
                </section>

                <!-- Section: Breaking the Stigma -->
                <section id="breaking-the-stigma" class="mb-12 scroll-target">
                    <h2 class="text-3xl font-bold text-primary mb-6">Breaking the Stigma</h2>
                    <p class="mb-6">
                        Stigma is one of the most significant barriers to mental health care. It manifests in various forms—from structural discrimination to internalized shame. When people believe that mental illness is a sign of weakness, they suffer in silence.
                    </p>
                    <blockquote>
                        "Stigma thrives in silence. By speaking openly about our mental health challenges, we dismantle the false narrative that struggling makes us less capable or less worthy."
                    </blockquote>
                    <p class="mb-6">
                        We can break the stigma by changing the language we use, treating mental health crises with the same urgency as medical emergencies, and sharing our own stories of recovery and resilience.
                    </p>
                </section>

