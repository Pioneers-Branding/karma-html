                    <h2 class="text-3xl font-bold text-primary mb-6">Why Mental Health Awareness Matters</h2>
                    <p class="mb-6">
                        Mental health is just as important as physical health, yet it is often overlooked or hidden due to societal pressures. Awareness matters because it saves lives. It normalizes the struggles many people face daily and provides a framework for seeking help without fear of judgment.
                    </p>
                    <div class="bg-purple-50 border-l-4 border-purple-500 rounded-r-xl p-6 mb-6">
