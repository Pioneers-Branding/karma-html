                            <a href="tms-therapy.php" class="text-primary hover:underline font-semibold">Transcranial Magnetic Stimulation (TMS)</a> is a non-invasive, FDA-cleared treatment that uses magnetic pulses to stimulate underactive areas of the brain. It is highly effective, safe, and typically free of the systemic side effects associated with traditional antidepressants.
