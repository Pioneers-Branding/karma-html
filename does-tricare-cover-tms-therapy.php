                    <h2 class="text-3xl font-bold text-primary mb-6">TRICARE Coverage for TMS Therapy</h2>
                    <p class="mb-6">
                        TRICARE is the healthcare program for uniformed service members, retirees, and their families worldwide. Over the last few years, TRICARE has expanded its coverage to include <strong>transcranial magnetic stimulation insurance</strong> options for those suffering from treatment-resistant depression.
                    </p>
                    <p class="mb-6">
                        According to <a href="https://en.wikipedia.org/wiki/Tricare" rel="nofollow" class="text-primary hover:underline">Wikipedia</a>, TRICARE provides civilian health benefits for U.S. Armed Forces military personnel. Their coverage of TMS is a significant step in supporting the mental health needs of the military community.
                    </p>
                    <h3 class="text-2xl font-bold text-gray-900 mb-4">What Conditions Does TRICARE Cover?</h3>
                    <p class="mb-4">Currently, TRICARE coverage is most robust for:</p>
                    <ul class="list-disc pl-5 mb-6">
                        <li><strong>Major Depressive Disorder (MDD):</strong> This is the primary condition for which TMS is covered.</li>
                        <li><strong>Treatment-Resistant Depression:</strong> Specifically for patients who have tried multiple medications without relief.</li>
                    </ul>
                    <p>While TMS is also used for <a href="ptsd.php" class="text-primary hover:underline">PTSD</a> and <a href="anxiety.php" class="text-primary hover:underline">anxiety</a>, coverage for these conditions under TRICARE may require additional documentation or be considered on a case-by-case basis.</p>
