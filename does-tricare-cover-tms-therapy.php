                    <h2 class="text-3xl font-bold text-primary mb-6">What is Transcranial Magnetic Stimulation (TMS)?</h2>
                    <p class="mb-6">
                        <a href="tms-therapy.php" class="text-primary hover:underline">TMS therapy</a> is a non-invasive procedure that uses magnetic fields to stimulate nerve cells in the brain. It is primarily used to treat <a href="depression.php" class="text-primary hover:underline">major depressive disorder</a>, particularly when other treatments haven't been effective.
                    </p>
                    <p class="mb-6">
                        During a session, an electromagnetic coil is placed against the scalp. The coil delivers painless magnetic pulses that reach specific areas of the brain involved in mood control. By stimulating these areas, TMS can help "reset" neural activity and alleviate symptoms of depression and <a href="ocd.php" class="text-primary hover:underline">OCD</a>.
                    </p>
