                <!-- Section: ADA -->
                <section id="ada" class="mb-12 scroll-target">
                    <h2 class="text-3xl font-bold text-primary mb-6">Is OCD Covered Under the ADA?</h2>
                    <p class="mb-6">
                        Yes, <strong>is ocd covered under ada</strong>? Absolutely. The Americans with Disabilities Act (ADA) defines a disability as a physical or mental impairment that substantially limits one or more major life activities. 
                    </p>
                    <p class="mb-6">
                        According to <a href="https://en.wikipedia.org/wiki/Obsessive%E2%80%93compulsive_disorder" rel="nofollow" class="text-primary hover:underline">Wikipedia</a>, OCD is a mental and behavioral disorder in which an individual has intrusive thoughts and feels the need to perform certain routines repeatedly. When these compulsions take up more than an hour a day or cause significant distress, they qualify as a substantial limitation.
                    </p>
                    <div class="bg-blue-50 border-l-4 border-blue-500 p-6 rounded-r-xl">
                        <p class="text-blue-900 font-medium">
                            Being covered under the ADA means you are entitled to "reasonable accommodations" at work or school to help you perform your duties effectively.
                        </p>
                    </div>
                </section>

                <!-- Section: Benefits -->
                <section id="benefits" class="mb-12 scroll-target">
                    <h2 class="text-3xl font-bold text-primary mb-6">OCD Disability Benefits</h2>
                    <p class="mb-6">
                        Beyond workplace protections, some individuals with severe OCD may be eligible for <strong>ocd disability benefits</strong> through the Social Security Administration (SSA).
                    </p>
                    <p class="mb-6">
                        To qualify for Social Security Disability Insurance (SSDI) or Supplemental Security Income (SSI), you must provide medical evidence that your OCD prevents you from engaging in "substantial gainful activity" (working) for at least 12 months.
                    </p>
                    <p>For more information on the process, see our guide on <a href="can-you-get-disability-for-depression.php" class="text-primary hover:underline">disability for mental health</a>, which follows a similar framework.</p>
                </section>

                <!-- Section: Symptoms -->
                <section id="symptoms" class="mb-12 scroll-target">
                    <h2 class="text-3xl font-bold text-primary mb-6">Recognizing Severe OCD Symptoms</h2>
                    <p class="mb-6">
                        Not all OCD is the same. While some people manage with mild symptoms, others experience <strong>severe OCD symptoms</strong> that make daily life nearly impossible. These can include:
                    </p>
                    <ul class="list-disc pl-5 mb-6">
                        <li><strong>Excessive Rituals:</strong> Spending several hours a day on compulsions like washing, checking, or counting.</li>
                        <li><strong>Crippling Obsessions:</strong> Intrusive thoughts that cause extreme terror or anxiety.</li>
                        <li><strong>Social Isolation:</strong> Avoiding people, places, or situations that trigger obsessions.</li>
                        <li><strong>Physical Distress:</strong> Symptoms like exhaustion from rituals or skin damage from excessive cleaning.</li>
                    </ul>
                </section>

