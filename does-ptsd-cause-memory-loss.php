                <section id="trauma-brain-neurobiology" class="mb-12 scroll-target">
                    <h2 class="text-3xl font-bold text-primary mb-6">How Trauma Alters Brain Architecture: The Neurobiology of Memory</h2>
                    <p class="mb-6">
                        To truly grasp why <strong>PTSD causes memory loss</strong>, one must look beneath psychological symptoms into neuroanatomy. Memory formation is not handled by a single brain component; it is an intricate neural network requiring seamless communication between three primary structures:
                    </p>

                    <div class="space-y-6 mb-8">
                        <div class="bg-white p-6 rounded-xl border border-gray-200 shadow-sm">
                            <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                                <span class="w-8 h-8 rounded-full bg-purple-100 text-primary flex items-center justify-center text-sm font-bold">1</span>
                                The Hippocampus: The Memory Filing Cabinet
                            </h3>
                            <p class="text-gray-600 mb-0">
                                Located within the medial temporal lobe, the hippocampus acts as the brain’s cataloger. It takes incoming sensory experiences, places them into a coherent chronological timeline (stamping them with "past," "present," or "future"), and transfers them into long-term declarative storage. In individuals suffering from PTSD, chronic hypercortisolemia (excess stress hormone) causes dendritic retraction and inhibits neurogenesis in the dentate gyrus. As a result, the hippocampus physically shrinks and loses its capacity to properly file both past memories and new daily details.
                            </p>
                        </div>

                        <div class="bg-white p-6 rounded-xl border border-gray-200 shadow-sm">
                            <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                                <span class="w-8 h-8 rounded-full bg-purple-100 text-primary flex items-center justify-center text-sm font-bold">2</span>
                                The Amygdala: The Hyperactive Alarm System
                            </h3>
                            <p class="text-gray-600 mb-0">
                                The amygdala governs threat assessment, fear conditioning, and autonomic fight-or-flight mobilization. In PTSD, the amygdala becomes structurally hyperactive and hypersensitive. It continuously screams that danger is imminent, flooding the nervous system with adrenaline. When the amygdala is operating in overdrive, it hijacks metabolic resources from the cognitive centers, sacrificing everyday memory encoding in favor of hypervigilant survival mode.
                            </p>
                        </div>

                        <div class="bg-white p-6 rounded-xl border border-gray-200 shadow-sm">
                            <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                                <span class="w-8 h-8 rounded-full bg-purple-100 text-primary flex items-center justify-center text-sm font-bold">3</span>
                                The Prefrontal Cortex (PFC): The Executive Administrator
                            </h3>
                            <p class="text-gray-600 mb-0">
                                The prefrontal cortex—specifically the dorsolateral prefrontal cortex (dlPFC) and ventromedial prefrontal cortex (vmPFC)—regulates working memory, impulse control, focused attention, and fear extinction. Under severe trauma, top-down PFC control is blunted. The prefrontal cortex loses its ability to quiet the hyperactive amygdala and fails to allocate working memory space for everyday problem-solving, making multitasking and short-term recall feel nearly impossible.
                            </p>
                        </div>
                    </div>

                    <p class="mb-6">
                        When this crucial triad falls out of synchrony, the brain stops processing reality cohesively. In our clinical work with veterans, first responders, and trauma survivors at our <a href="ptsd-treatment-palm-springs.php" class="text-primary hover:underline">Palm Springs PTSD clinic</a>, quantitative EEG (qEEG) <a href="brain-mapping.php" class="text-primary hover:underline">brain mapping</a> frequently shows these exact dysregulated connectivity patterns across prefrontal and limbic networks.
                    </p>
