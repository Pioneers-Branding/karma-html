        window.toggleBlogFAQ = function(button) {
            const currentItem = button.parentElement;
            const isAlreadyOpen = currentItem.getAttribute('data-state') === 'open';
            document.querySelectorAll('.accordion-item').forEach(item => {
                item.setAttribute('data-state', 'closed');
                const content = item.querySelector('.accordion-content');
                if (content) { content.style.maxHeight = '0px'; }
            });
            if (!isAlreadyOpen) {
                currentItem.setAttribute('data-state', 'open');
                const content = currentItem.querySelector('.accordion-content');
                if (content) { content.style.maxHeight = content.scrollHeight + 'px'; }
            }
        };

        document.addEventListener('DOMContentLoaded', function () {
            const sections = document.querySelectorAll('.scroll-target');
            const navButtons = document.querySelectorAll('.toc-button');

            function highlightNavigation() {
                const scrollPosition = window.scrollY + 180;
                let activeId = '';

                // Find the latest section that has been scrolled into view
                sections.forEach(section => {
                    if (scrollPosition >= section.offsetTop) {
                        activeId = section.getAttribute('id');
                    }
                });

                // If scrolled to the bottom of the page, activate the last section
                if ((window.innerHeight + window.scrollY) >= (document.documentElement.scrollHeight - 60)) {
                    if (sections.length > 0) {
                        activeId = sections[sections.length - 1].getAttribute('id');
                    }
                }

                navButtons.forEach(btn => {
                    const onclickAttr = btn.getAttribute('onclick') || '';
                    if (activeId && onclickAttr.includes("'" + activeId + "'")) {
                        btn.classList.add('active');
                    } else {
                        btn.classList.remove('active');
                    }
                });
            }

            let isScrolling = false;
            window.addEventListener('scroll', function () {
                if (!isScrolling) {
                    window.requestAnimationFrame(function () {
                        highlightNavigation();
                        isScrolling = false;
                    });
                    isScrolling = true;
                }
            }, { passive: true });

            highlightNavigation();

            window.scrollToSection = function(id) {
                const element = document.getElementById(id);
                if (element) {
                    navButtons.forEach(btn => {
                        const onclickAttr = btn.getAttribute('onclick') || '';
                        if (onclickAttr.includes("'" + id + "'")) {
                            btn.classList.add('active');
                        } else {
                            btn.classList.remove('active');
                        }
                    });
                    const headerOffset = 100;
                    const elementPosition = element.getBoundingClientRect().top;
                    const offsetPosition = elementPosition + window.pageYOffset - headerOffset;
                    window.scrollTo({ top: offsetPosition, behavior: "smooth" });
                }
            };

            if (window.lucide) {
                lucide.createIcons();
            }
        });
    </script>
