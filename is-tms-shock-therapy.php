                    <h2 class="text-3xl font-bold text-primary mb-6">What Is TMS Therapy?</h2>
                    <p class="mb-6">
                        <strong>Transcranial Magnetic Stimulation (TMS)</strong> is a non-invasive, FDA-cleared treatment that uses precisely targeted magnetic pulses to stimulate specific areas of the brain involved in mood regulation — specifically the left dorsolateral prefrontal cortex.
                    </p>
                    <p class="mb-6">
                        Think of it like a physical therapy session for your brain. Just as a physical therapist uses targeted exercise to strengthen a specific muscle, TMS uses magnetic energy to strengthen specific neural pathways that have become underactive in conditions like <a href="depression.php" class="text-primary hover:underline">depression</a> and <a href="anxiety.php" class="text-primary hover:underline">anxiety</a>.
                    </p>
                    <p class="mb-6">
                        During a TMS session, a small coil is placed gently against the scalp. It emits brief magnetic pulses — similar in strength to an MRI machine — that pass through the skull and into the brain without causing pain or requiring any invasive procedure.
                    </p>
