                    <ul class="list-disc pl-6 space-y-2 text-gray-700 mb-6">
                        <li><strong>Linguistic drift:</strong> The word "shock" has been loosely applied to any treatment involving electricity or magnetic energy. In common usage, it has become a catch-all term for brain stimulation — regardless of mechanism or intensity.</li>
                        <li><strong>ECT's legacy:</strong> The phrase "shock therapy" was historically associated with <a href="https://en.wikipedia.org/wiki/Electroconvulsive_therapy" target="_blank" rel="noopener noreferrer" class="text-primary hover:underline">Electroconvulsive Therapy (ECT)</a>, an older procedure that does involve electrical current and sedation. Although modern ECT is far safer than its reputation suggests, the association with "shock" has unfairly colored public perception of all brain stimulation therapies.</li>
                    </ul>
