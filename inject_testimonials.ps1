    if (-not (Test-Path $filePath)) {
        Write-Host "File not found: $($page.File)"
        continue
    }

    $content = Get-Content $filePath -Raw

    # Generate HTML
    $html = @"

    <!-- Patient Testimonials -->
    <section class="py-16 px-4 bg-gray-50">
