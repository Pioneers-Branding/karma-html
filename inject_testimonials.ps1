                    <p class="text-gray-700 italic mb-6 leading-relaxed">"$($review.Quote)"</p>
                    <div class="flex items-center gap-4">
                        <div class="w-12 h-12 bg-purple-100 rounded-full flex items-center justify-center text-primary-brand font-bold text-xl">$initial</div>
                        <div>
                            <h4 class="font-bold text-gray-900">$($review.Name)</h4>
                            <p class="text-sm text-gray-500">$($review.Location)</p>
                        </div>
                    </div>
                </div>
"@
    }

    $html += @"

            </div>
            
            <div class="text-center mt-12 fade-in-up">
                <a href="testimonials.php" class="inline-flex items-center gap-2 px-6 py-3 border-2 border-primary-brand text-primary-brand rounded-md font-semibold hover:bg-primary-brand hover:text-white transition">
                    View All Testimonials
                    <i data-lucide="arrow-right" class="w-4 h-4"></i>
                </a>
            </div>
        </div>
    </section>
"@

    # Check if we already injected it
    if ($content -match "<!-- Patient Testimonials -->") {
        Write-Host "Already has testimonials: $($page.File)"
        continue
    }

    # Inject logic: try to find '<!-- Final CTA' or '<!-- CTA Section' or '<!-- Final CTA Section'
    # If not found, insert before '<?php include 'includes/footer.php'; ?>'
    $injected = $false

    # Regex patterns to find injection points
    $patterns = @(
        "(\s*<!--\s*(?:Final\s*)?CTA(?:\s*Section)?\s*-->)",
        "(\s*<\?php\s*include\s*'includes/footer\.php';\s*\?>)"
    )

    foreach ($pattern in $patterns) {
        if ($content -match $pattern) {
            $replacement = "`n$html`n`n`$1"
            $content = $content -replace $pattern, $replacement
            $injected = $true
            break
        }
    }

    if ($injected) {
        Set-Content -Path $filePath -Value $content -Encoding UTF8
        Write-Host "Injected into $($page.File)"
    } else {
        Write-Host "Failed to find injection point in $($page.File)"
    }
}
