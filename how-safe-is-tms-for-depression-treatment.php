                                Auditory Clicking Noise
                            </h3>
                            <p class="text-gray-700 m-0">
                                The TMS device produces an audible clicking sound similar to a woodpecker or mechanical typewriter as electromagnetic coils discharge. To protect your hearing and ensure complete acoustic comfort, all patients are provided with disposable foam earplugs before every session.
                            </p>
                        </div>
                    </div>

                    <p class="mb-6">
