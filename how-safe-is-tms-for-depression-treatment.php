                            <h3 class="text-lg font-bold text-gray-900 flex items-center gap-2 mb-2">
                                <i data-lucide="activity" class="w-5 h-5 text-primary"></i>
                                Scalp Discomfort or Tingling (Most Common)
                            </h3>
                            <p class="text-gray-700 m-0">
                                During active stimulation, patients feel a rhythmic tapping or clicking sensation against the scalp. Because the scalp contains sensitive nerve endings, early sessions may feel strange or slightly uncomfortable. In virtually all cases, the scalp adapts within 5 to 10 treatment sessions as the sensory threshold acclimates.
                            </p>
                        </div>

                        <div class="p-5 bg-white rounded-xl border border-gray-200 shadow-xs">
                            <h3 class="text-lg font-bold text-gray-900 flex items-center gap-2 mb-2">
                                <i data-lucide="zap" class="w-5 h-5 text-primary"></i>
                                Mild Tension Headache
                            </h3>
                            <p class="text-gray-700 m-0">
                                Roughly one-third of patients experience a mild, dull tension headache following their first few daily sessions. These headaches typically dissipate within 30 to 45 minutes and respond promptly to common over-the-counter pain relievers such as acetaminophen or ibuprofen.
                            </p>
                        </div>

                        <div class="p-5 bg-white rounded-xl border border-gray-200 shadow-xs">
                            <h3 class="text-lg font-bold text-gray-900 flex items-center gap-2 mb-2">
                                <i data-lucide="smile" class="w-5 h-5 text-primary"></i>
                                Temporary Facial Muscle Twitching
                            </h3>
                            <p class="text-gray-700 m-0">
                                Because magnetic pulses can stimulate nearby peripheral nerves that control superficial facial muscles, patients may observe mild involuntary eyelid or jaw twitching during pulse trains. This is completely harmless, occurs only while pulses are firing, and stops instantly between trains.
                            </p>
                        </div>

                        <div class="p-5 bg-white rounded-xl border border-gray-200 shadow-xs">
                            <h3 class="text-lg font-bold text-gray-900 flex items-center gap-2 mb-2">
