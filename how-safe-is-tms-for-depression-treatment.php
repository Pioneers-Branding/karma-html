                    <h2 class="text-3xl font-bold text-primary mb-6">What Are the Common Side Effects of TMS Therapy?</h2>
                    <p class="mb-6">
                        While TMS has an exceptional safety profile, it is a medical procedure, and mild, transient physical sensations can occur. Over 95% of side effects reported in clinical trials are mild to moderate, localized strictly to the treatment site, and resolve spontaneously shortly after each session finishes.
                    </p>
                    <p class="mb-6">
