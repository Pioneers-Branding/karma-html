                    <h2 class="text-3xl font-bold text-primary mb-6">What Is TMS Therapy? A Quick Clinical Overview</h2>
                    <p class="mb-6">
                        <a href="tms-therapy.php" class="text-primary ">Transcranial Magnetic Stimulation (TMS)</a> is an FDA-cleared, non-invasive brain stimulation therapy that uses precisely targeted, MRI-strength magnetic pulses to stimulate underactive neural circuits in the brain — most commonly in the dorsolateral prefrontal cortex (dlPFC). It is primarily used to treat <a href="depression.php" class="text-primary ">major depressive disorder (MDD)</a> in patients who have not responded adequately to antidepressant medications.
