                    </p>
                    <p class="mb-6">
                        As a Medi-Cal managed care organization (MCO), IEHP coordinates care through a network of contracted providers, hospitals, and specialty clinics. When it comes to <strong>mental health coverage</strong>, IEHP offers benefits including psychiatric evaluations, outpatient therapy, medication management, and advanced treatments like TMS therapy — when medical necessity is documented and prior authorization is obtained.
                    </p>

