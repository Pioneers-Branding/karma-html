                                FDA-Cleared Since 2008
                            </h3>
                            <p class="text-gray-600 mb-0">
                                The U.S. Food and Drug Administration first cleared TMS for treatment-resistant depression in 2008. Since then, TMS has received additional FDA clearances for OCD (2018) and smoking cessation (2020), and continues to be studied for anxiety, PTSD, and other conditions.
