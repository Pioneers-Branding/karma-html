                                Non-Invasive &amp; Medication-Free
                            </h3>
                            <p class="text-gray-600 mb-0">
                                TMS requires no anesthesia, no surgery, and no systemic medications. Patients sit comfortably in a reclining chair during each 20–40 minute session and return to normal activities immediately afterward — including driving.
                            </p>
                        </div>

                        <div class="bg-white p-6 rounded-xl border border-gray-200 shadow-sm">
                            <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
