      <section id="common-side-effects" class="mb-12 scroll-target">
        <h2 class="text-3xl font-bold text-primary mb-6">Common Side Effects of TMS Therapy</h2>
        <p class="mb-6">
          The majority of patients tolerate TMS therapy extremely well. Because the treatment uses magnetic fields to stimulate specific areas of the brain (rather than chemicals that travel throughout the entire body), the side effects are localized to the treatment area. The most common side effects include:
        </p>
        <ul class="list-disc pl-6 space-y-2 text-gray-700">
          <li><strong>Scalp Discomfort:</strong> The most frequently reported side effect is a mild tapping, tingling, or uncomfortable sensation on the scalp at the treatment site. This occurs during the magnetic pulses.</li>
          <li><strong>Mild Headaches:</strong> About half of patients report mild headaches following their initial sessions. These are typically easily managed with over-the-counter pain relievers like ibuprofen or acetaminophen.</li>
          <li><strong>Facial Muscle Twitching:</strong> Some patients experience slight twitching of the jaw or facial muscles during the treatment pulse. This stops immediately when the pulse ends.</li>
          <li><strong>Lightheadedness:</strong> A very small percentage of patients may feel briefly lightheaded immediately following a session, though this is rare.</li>
        </ul>
      </section>

      <section id="rare-side-effects" class="mb-12 scroll-target">
        <h2 class="text-3xl font-bold text-primary mb-6">Rare but Serious Side Effects</h2>
        <p class="mb-6">
          While TMS is highly safe, it is a medical procedure and carries a very small risk of more serious side effects.
        </p>
        <ul class="list-disc pl-6 space-y-2 text-gray-700">
          <li><strong>Seizures:</strong> The most significant risk associated with TMS is a seizure. However, this risk is exceedingly rare—occurring in less than 0.1% of patients. The risk is comparable to or lower than the seizure risk associated with many common antidepressant medications.</li>
          <li><strong>Hearing Issues:</strong> Because the TMS machine produces a loud clicking sound (similar to an MRI machine), there is a theoretical risk of hearing damage. However, patients are provided with earplugs during every session, which effectively eliminates this risk.</li>
        </ul>
      </section>
