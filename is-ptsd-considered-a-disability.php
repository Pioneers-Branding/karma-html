                <section id="social-security" class="mb-12 scroll-target">
                    <h2 class="text-3xl font-bold text-primary mb-6">Is PTSD a Disability for Social Security?</h2>
                    <p class="mb-6">
                        Yes. The Social Security Administration (SSA) lists PTSD in its <a href="https://www.ssa.gov/disability/professionals/bluebook/12.00-MentalDisorders-Adult.htm" target="_blank" rel="noopener noreferrer" class="text-primary hover:underline font-medium">Blue Book of mental disorders</a> under <strong>listing 12.15, trauma- and stressor-related disorders</strong>. To meet the listing, your records must show both Part A and either Part B or Part C.
                    </p>

                    <h3 class="text-2xl font-bold text-gray-900 mb-4">Part A: Medical Documentation of PTSD Symptoms</h3>
                    <p class="mb-4">Your medical records must document all of the following:</p>
                    <ul class="space-y-2 mb-6">
                        <li>Exposure to actual or threatened death, serious injury, or violence</li>
                        <li>Involuntary re-experiencing of the event, such as flashbacks, nightmares, or intrusive memories</li>
                        <li>Avoidance of reminders of the trauma</li>
                        <li>Disturbances in mood and behavior</li>
                        <li>Increased arousal and reactivity, such as an exaggerated startle response or sleep problems</li>
                    </ul>

                    <h3 class="text-2xl font-bold text-gray-900 mb-4">Part B or Part C: Functional Limitations</h3>
                    <p class="mb-4">
                        <strong>Part B</strong> requires an extreme limitation in one, or a marked limitation in two, of these areas:
                    </p>
                    <ul class="space-y-2 mb-6">
                        <li>Understanding, remembering, or applying information</li>
                        <li>Interacting with others</li>
                        <li>Concentrating, persisting, or maintaining pace</li>
                        <li>Adapting or managing oneself</li>
                    </ul>
                    <p class="mb-6">
                        <strong>Part C</strong> applies when PTSD is "serious and persistent": a medically documented history of at least two years, ongoing treatment or a highly structured setting that reduces your symptoms, and only a minimal capacity to adapt to changes or new demands.
                    </p>

                    <h3 class="text-2xl font-bold text-gray-900 mb-4">What If You Don't Meet the Listing?</h3>
                    <p class="mb-6">
