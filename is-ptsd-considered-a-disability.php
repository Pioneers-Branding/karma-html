                    <h2 class="text-3xl font-bold text-primary mb-6">Is PTSD a Disability Under the ADA?</h2>
                    <p class="mb-6">
                        In most cases, yes. Under the Americans with Disabilities Act (ADA), a disability is an impairment that substantially limits a major life activity. EEOC regulations specifically name PTSD as a condition that should easily be found to substantially limit brain function. The ADA applies to employers with 15 or more employees, and California's Fair Employment and Housing Act (FEHA) goes further, covering employers with five or more employees and using a broader "limits" standard.
                    </p>
                    <p class="mb-4">Common reasonable accommodations for PTSD include:</p>
                    <ul class="space-y-2 mb-6">
                        <li>Flexible schedules or time off for therapy and medical appointments</li>
                        <li>A quieter workspace, noise-canceling headphones, or a seat facing the door</li>
                        <li>Written instructions and task checklists to support memory and focus</li>
                        <li>Remote or hybrid work when job duties allow</li>
                        <li>Advance notice of changes, drills, or loud events</li>
                        <li>Permission to take short breaks to manage panic or flashbacks</li>
                    </ul>
                    <div class="bg-blue-50 border-l-4 border-blue-200 p-6 rounded-r-xl mb-6">
                        <h3 class="font-bold text-blue-900 text-xl mb-2">Do You Have to Tell Your Employer You Have PTSD?</h3>
                        <p class="text-blue-900 mb-0">
                            No. You only need to disclose a disability if you are requesting an accommodation. Even then, your employer may ask for reasonable medical documentation, but your diagnosis must be kept confidential and separate from your personnel file.
                        </p>
                    </div>
                    <p class="mb-6">
                        Short-term options also exist. California State Disability Insurance (SDI) can provide partial wage replacement if a licensed provider certifies that PTSD temporarily prevents you from working.
                    </p>
                </section>

